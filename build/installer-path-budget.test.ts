import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

import { afterEach, describe, expect, it } from 'vitest'

// @ts-expect-error -- plain CommonJS build script
import {
  WINDOWS_MAX_USABLE_PATH,
  assessInstallTarget,
  collectRelativePathLengths,
  emit,
  renderInclude,
  summarize
} from './installer-path-budget.cjs'

const roots: string[] = []
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true })
})

/** A payload tree with the given relative paths (files only). */
const payload = (paths: string[]): string => {
  const root = mkdtempSync(join(tmpdir(), 'installer-budget-'))
  roots.push(root)
  for (const relative of paths) {
    const absolute = join(root, ...relative.split('/'))
    mkdirSync(join(absolute, '..'), { recursive: true })
    writeFileSync(absolute, '')
  }
  return root
}

describe('installer path budget (#163)', () => {
  it('measures every file as a backslashed relative path including its separator', () => {
    const root = payload(['app.exe', 'resources/app.asar', 'resources/deep/one.bin'])
    // \app.exe (8), \resources\app.asar (19), \resources\deep\one.bin (23)
    expect(collectRelativePathLengths(root).sort((a, b) => a - b)).toEqual([8, 19, 23])
  })

  it('counts files that would exceed the limit for a folder, and reports the longest', () => {
    // Limit 259: a folder of 240 characters leaves 19 for a relative path.
    const summary = summarize([8, 19, 24, 24])
    const assessment = assessInstallTarget('C:\\' + 'x'.repeat(237), summary)

    expect(assessment.installDirLength).toBe(240)
    expect(assessment.limit).toBe(WINDOWS_MAX_USABLE_PATH)
    // 240 + 8 and 240 + 19 fit (<= 259); the two 24-byte paths need 264.
    expect(assessment.overflowFiles).toBe(2)
    expect(assessment.longestPathLength).toBe(264)
    expect(assessment.maxInstallDirLength).toBe(259 - 24)
  })

  it('passes a folder that is short enough, including the classic default', () => {
    const summary = summarize([8, 19, 24])
    expect(assessInstallTarget('C:\\Program Files\\Baselio', summary).overflowFiles).toBe(0)
  })

  it('reports the exact boundary: the last fitting folder is limit minus the longest path', () => {
    const summary = summarize([30])
    const limit = 259
    const longestFitting = 'C:\\' + 'y'.repeat(limit - 30 - 3)
    expect(assessInstallTarget(longestFitting, summary).overflowFiles).toBe(0)
    const oneMore = `${longestFitting}y`
    expect(assessInstallTarget(oneMore, summary).overflowFiles).toBe(1)
  })

  it('emits an include whose bucket thresholds reproduce the assessment', () => {
    const summary = summarize([8, 19, 24, 24])
    const include = renderInclude(summary)
    expect(include).toContain('!define BASELIO_PAYLOAD_FILES 4')
    expect(include).toContain('!define BASELIO_MAX_RELATIVE_PATH 24')
    expect(include).toContain(`!define BASELIO_MAX_INSTALL_DIR_LENGTH ${259 - 24}`)
    // Every bucket carries the constant threshold "folder length > limit - relative".
    expect(include).toContain('${If} $R1 > 251')
    expect(include).toContain('IntOp $R3 $R3 + 2')
    expect(include).toContain('${If} $R1 > 240')
  })

  it('writes the include from a real directory tree', () => {
    const root = payload(['app.exe', 'resources/a/b/c.bin'])
    const out = join(root, 'budget.nsh')
    const summary = emit({ payloadDir: root, out })

    expect(summary.files).toBe(2)
    expect(summary.maxRelative).toBe('\\resources\\a\\b\\c.bin'.length)
    const written = readFileSync(out, 'utf8')
    expect(written).toContain('; Generated by build/installer-path-budget.cjs')
    expect(written).toContain(`!define BASELIO_MAX_RELATIVE_PATH ${summary.maxRelative}`)
  })

  it('refuses an empty payload instead of emitting a budget that would pass everything', () => {
    const root = payload([])
    expect(() => emit({ payloadDir: root, out: join(root, 'budget.nsh') })).toThrow(
      /No files to measure/
    )
  })
})
