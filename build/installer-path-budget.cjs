/* Build-time path budget for the NSIS preflight (#163).
 *
 * A Windows install fails once any file's absolute path exceeds MAX_PATH. The installer cannot see its
 * own payload's path lengths at runtime, so they are measured here, at packaging time, and emitted as a
 * small NSIS include: the longest relative path plus a histogram of every relative path length. The
 * installer then answers "how many files would be too long for the folder the user picked" for any
 * folder, because that is a pure function of the folder length and those lengths.
 *
 * The limit is 259, not 260: MAX_PATH counts the terminating NUL, the same convention the runtime's
 * package-cache budget uses (packages/environment/src/micromamba-cache.ts). The measured value is the
 * full absolute path, so it includes the drive letter, the folder and its separators.
 */
const fs = require('node:fs')
const path = require('node:path')

const WINDOWS_MAX_USABLE_PATH = 259

/** Every file under `payloadDir`, as `\relative\path` lengths (the leading separator included). */
const collectRelativePathLengths = (payloadDir) => {
  const lengths = []
  const walk = (dir, prefix) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const absolute = path.join(dir, entry.name)
      const relative = `${prefix}${entry.name}`
      if (entry.isDirectory()) walk(absolute, `${relative}\\`)
      // +1 for the separator that joins this path to the install folder: the measured value is what gets
      // appended to $INSTDIR, not the bare file name.
      else if (entry.isFile() || entry.isSymbolicLink()) lengths.push(relative.length + 1)
    }
  }
  walk(payloadDir, '')
  return lengths
}

/** Longest relative path and a length -> count histogram, sorted by length. */
const summarize = (lengths) => {
  const histogram = new Map()
  let maxRelative = 0
  for (const length of lengths) {
    histogram.set(length, (histogram.get(length) ?? 0) + 1)
    if (length > maxRelative) maxRelative = length
  }
  return {
    files: lengths.length,
    maxRelative,
    buckets: [...histogram].sort((left, right) => left[0] - right[0])
  }
}

/**
 * What the installer needs to know for one candidate folder.
 * `installDir` is the folder the user picked; the longest file inside it decides the verdict.
 */
const assessInstallTarget = (installDir, summary, limit = WINDOWS_MAX_USABLE_PATH) => {
  const installDirLength = installDir.length
  let overflowFiles = 0
  for (const [relative, count] of summary.buckets) {
    if (installDirLength + relative > limit) overflowFiles += count
  }
  return {
    installDirLength,
    limit,
    overflowFiles,
    longestPathLength: installDirLength + summary.maxRelative,
    maxInstallDirLength: limit - summary.maxRelative
  }
}

const escapeNsis = (value) =>
  value.replaceAll('$', '$$').replaceAll('"', '$\\"').replaceAll('\\', '\\\\')

/** The include the installer reads: constants, the longest relative path, and the counting code. */
const renderInclude = (summary, { limit = WINDOWS_MAX_USABLE_PATH } = {}) => {
  const lines = [
    '; Generated by build/installer-path-budget.cjs. Do not edit; it is rewritten by the beforePack hook.',
    '; Relative lengths are measured from the packaged payload; the limit matches MAX_PATH minus the NUL.',
    `!ifndef BASELIO_PATH_LIMIT`,
    `!define BASELIO_PATH_LIMIT ${limit}`,
    `!endif`
  ]
  lines.push(`!define BASELIO_PAYLOAD_FILES ${summary.files}`)
  lines.push(`!define BASELIO_MAX_RELATIVE_PATH ${summary.maxRelative}`)
  lines.push(`!define BASELIO_MAX_INSTALL_DIR_LENGTH ${Math.max(0, limit - summary.maxRelative)}`)
  lines.push('')
  lines.push(
    '; Counts payload files whose absolute path would exceed the limit for a given folder.'
  )
  lines.push('; Input: $R1 = StrLen(folder). Output: $R3 = number of files that would be too long.')
  lines.push('!macro baselioCountOverflowingFiles')
  lines.push('  StrCpy $R3 0')
  for (const [relative, count] of summary.buckets) {
    // InstallDir + relative > limit  <=>  InstallDir > limit - relative, all constants but $R1.
    lines.push(`  \${If} $R1 > ${limit - relative}`)
    lines.push(`    IntOp $R3 $R3 + ${count}`)
    lines.push('  ${EndIf}')
  }
  lines.push('!macroend')
  lines.push('')
  return `${lines.join('\n')}\n`
}

const emit = ({ payloadDir, out, limit = WINDOWS_MAX_USABLE_PATH }) => {
  const summary = summarize(collectRelativePathLengths(payloadDir))
  if (summary.files === 0) throw new Error(`No files to measure under ${payloadDir}`)
  fs.writeFileSync(out, renderInclude(summary, { limit }))
  return summary
}

module.exports = {
  WINDOWS_MAX_USABLE_PATH,
  assessInstallTarget,
  collectRelativePathLengths,
  emit,
  renderInclude,
  summarize
}

if (require.main === module) {
  const args = process.argv.slice(2)
  const value = (name) => {
    const index = args.indexOf(`--${name}`)
    return index === -1 ? undefined : args[index + 1]
  }
  const payloadDir = value('payload')
  const out = value('out')
  if (!payloadDir || !out) {
    console.error('usage: node build/installer-path-budget.cjs --payload <dir> --out <file.nsh>')
    process.exit(2)
  }
  const summary = emit({ payloadDir, out })
  const example = assessInstallTarget('C:\\Program Files\\Baselio', summary)
  console.log(
    `payload files ${summary.files}, longest relative path ${summary.maxRelative}, ` +
      `longest folder ${example.maxInstallDirLength} characters; ` +
      `C:\\Program Files\\Baselio would have ${example.overflowFiles} files over the limit`
  )
}
